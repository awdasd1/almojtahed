matched_sections = []
for sec in user_categories:
    sec_name = sec["category"]
    sec_books = []
    for title_kw, author_kw in sec["items"]:
        c.execute("""
            SELECT book_id, title_ar, main_author_name_ar, category_name_ar, volume_count_observed 
            FROM books 
            WHERE title_ar LIKE ?
            ORDER BY 
                CASE WHEN main_author_name_ar LIKE ? THEN 0 ELSE 1 END,
                volume_count_observed DESC 
            LIMIT 1
        """, (f"%{title_kw}%", f"%{author_kw}%"))
        row = c.fetchone()
        if row:
            sec_books.append({
                "book_id": row[0],
                "title_ar": row[1],
                "author": row[2] or author_kw,
                "category": row[3] or sec_name,
                "selected": True
            })
        else:
            sec_books.append({
                "book_id": None,
                "title_ar": title_kw,
                "author": author_kw,
                "category": sec_name,
                "selected": True
            })
    matched_sections.append({
        "section_name": sec_name,
        "books": sec_books
    })

